    private void navColors(){
        Painter<JToggleButton> backgroundPainter = (graphics, button, width,
                height) -> {
            graphics.setColor(button.isSelected() ? new Color(32, 61, 104) :
                    new Color(19, 30, 47));
            graphics.fillRoundRect(0, 0, width, height, 10, 10);
        };
        String[] states = {
            "Enabled",
            "Focused",
            "MouseOver",
            "Pressed",
            "Selected",
            "Focused+MouseOver",
            "Focused+Pressed",
            "Focused+Selected",
            "MouseOver+Selected",
            "Pressed+Selected",
            "Focused+MouseOver+Selected",
            "Focused+Pressed+Selected"
        };
        UIDefaults overrides = new UIDefaults();
        for (String state : states) {
            overrides.put(
                "ToggleButton[" + state + "].backgroundPainter",
                backgroundPainter
            );
        }
        JToggleButton[] buttons = {
            dashboardBTN,
            stockMarketBTN,
            orderbookBTN,
            placeorderBTN,
            myportfolioBTN,
            myorderBTN,
            tradehistoryBTN,
            marketsimBTN
        };
        for (JToggleButton button : buttons) {
            button.putClientProperty("Nimbus.Overrides", overrides);
        }
    }

